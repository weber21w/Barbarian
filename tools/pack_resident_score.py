"""Pack every immutable native-player read from the closed pattern graph.

The program counter and one-slot return state determine command order; duration
and PWM clocks change scheduling only. Pitch modulation is covered separately
by its complete normalized index range, independent of captured-loop phase.
"""
from pathlib import Path
import json,hashlib
R=Path(__file__).resolve().parents[1]
blob=(R/'resources/misc/Barbarian.sid').read_bytes();assert hashlib.sha256(blob).hexdigest()=='c4eb468aa466b34de46dedbb166a0941b10adb3f20809f7cce670ab878071e6a','SID changed: re-audit the native player before rebuilding'
at=int.from_bytes(blob[6:8],'big');load=int.from_bytes(blob[at:at+2],'little');payload=blob[at+2:];used=set()
def byte(a):
 assert load<=a<load+len(payload),hex(a);used.add(a);return payload[a-load]
def word(a):return byte(a)|(byte(a+1)<<8)
def block(a,n):return bytes(byte(a+i) for i in range(n))
# Any pitch update normalizes its eight-bit result to 0..192. Static initial
# note values are additionally read below, even if outside that bound.
block(0x9d73,193*2)
reports=[];kinds=set();notes=set();commands=set();instruments=set()
for song in range(3):
 for voice in range(3):
  seed=byte((0xb550,0xb560,0xb570)[voice]+song)
  if not seed&128:reports.append(dict(song=song+1,voice=voice,states=0,stopped=True));continue
  pat,off,ret,ret_off=seed,0,0,0;seen=set();yielded=False
  while (pat,off,ret,ret_off) not in seen:
   seen.add((pat,off,ret,ret_off));assert len(seen)<1000000
   p=(word(0xa029+((pat*2)&255))+off)&65535;c=byte(p);count=0;yielded=False
   if c<0xc0:notes.add(c);word(0x9d73+2*((c*2)&255));count=1;yielded=True
   elif c<0xd0:word(0x9ef3+(c&15)*2);count=1
   else:
    commands.add(c)
    if c==0xf0:count=1;yielded=True
    elif c==0xf3:
     a=byte(p+1);b=block(0xa23c+a*12,12);instruments.add(a);kinds.add(b[2]&0xf0);assert not b[5]&0x16,('unsupported instrument',a,b[5]);count=2
    elif c==0xf4:
     word(0x9ef3+(byte(p+1)&15)*2);word(0x9ef3+(byte(p+2)&15)*2);count=3
    elif c==0xf5:pat=byte(p+1)|128;off=0
    elif c==0xf6:word(0x9f13+((byte(p+1)*2)&255));count=2
    elif c==0xf7:ret,ret_off=pat,(off+2)&65535;pat=byte(p+1)|128;off=0
    elif c==0xf8:pat,off=ret,ret_off
    elif c==0xf9:block(word(0x9f59+((byte(p+1)*2)&255)),11);count=2
    else:raise AssertionError(('unimplemented reachable command',song+1,voice,hex(p),hex(c)))
   off=(off+count)&65535
   if yielded and not pat&128:break
  reports.append(dict(song=song+1,voice=voice,states=len(seen),stopped=yielded and not bool(pat&128)))
assert kinds<={0,16,32,64}
ranges=[];packed=bytearray()
for a in sorted(used):
 if ranges and a==ranges[-1]['address']+ranges[-1]['bytes']:ranges[-1]['bytes']+=1
 else:ranges.append(dict(address=a,offset=len(packed),bytes=1))
 packed.append(payload[a-load])
result=dict(source_sha256=hashlib.sha256(blob).hexdigest(),bytes=len(packed),sha256=hashlib.sha256(packed).hexdigest(),ranges=ranges,closure=reports,initial_notes=sorted(notes),instruments=sorted(instruments),commands=sorted(commands),frequency_entries=193,method='complete pattern and one-slot return-state traversal; all possible normalized pitch indices')
(R/'data/resident-score-layout.json').write_text(json.dumps(result,indent=2)+'\n')
(R/'data/BARB-SCORE.DAT').write_bytes(packed)
count=len(ranges);assert 0<count<256
mapping='/* Generated by pack_resident_score.py: complete control-flow closure. */\n'
mapping+=f'#define BARB_SCORE_RANGE_COUNT {count}\n'
mapping+=f'static const uint16_t starts[{count}] PROGMEM={{'+','.join(str(r['address']) for r in ranges)+'};\n'
mapping+=f'static const uint16_t biases[{count}] PROGMEM={{'+','.join(str(r['address']-r['offset']) for r in ranges)+'};\n'
(R/'data/resident-score-map.inc').write_text(mapping)
print('Resident music:',len(packed),'bytes,',count,'ranges,',sum(r['states'] for r in reports),'closed control states; all 193 normalized pitch indices included')
