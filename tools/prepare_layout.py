"""Pack the tall display and sprite poses around the fixed ADPCM sound bank."""
from pathlib import Path
import json,re
R=Path(__file__).resolve().parents[1]
sprites=(R/'data/BARB-SPC.DAT').stat().st_size
resident=json.loads((R/'data/pose-resident.json').read_text())
directory=(R/'data/sprite-spanfmt.inc').read_text()
offsets=[e['offset'] for e in resident['entries']]
sizes=[e['stored'] for e in resident['entries']]
assert len(offsets)==len(sizes)
cursor=0
for offset,size in zip(offsets,sizes):
    assert offset==cursor,'AVR pose loader requires contiguous frames in directory order'
    cursor+=size
cache=int(re.search(r'BARB_SPRITE_CACHE_BYTES\s+(\d+)',directory)[1])
frame=214*128//2;sfx=65536
poses=resident['pose_bytes']
assert cursor==poses,'Pose directory must cover the complete contiguous bank'
runtime=resident['runtime_bytes']
menu=(R/'data/menu.raw').stat().st_size
assert sprites==poses+runtime+menu
runtime_base=3*frame
pose_base=runtime_base+runtime
sfxbytes=int(re.search(r'BARB_AUDIO_DATA_BYTES\s+(\d+)',(R/'platform/audio.h').read_text())[1])
split=max(o for o in offsets if o<=sfx-128-pose_base)
assert all(o+n<=split or o>=split for o,n in zip(offsets,sizes)),'A pose straddles banks'
ahead=sfx-128
assert pose_base+split<=ahead,'Resident poses overlap the music-ahead queue'
scorebytes=(R/'data/BARB-SCORE.DAT').stat().st_size
tail=sfx+sfxbytes;sid=(tail+poses-split+15)&~15
assert sid>>16==1 and sid+scorebytes<=131072,'Score must remain within SPI bank 1'
regions=[('front',0,frame),('back',frame,frame),('background',2*frame,frame),
 ('runtime',runtime_base,runtime),('sprites0',pose_base,split),('music_ahead',ahead,128),('effects',sfx,sfxbytes),('sprites1',tail,poses-split),
 ('music',sid,scorebytes),('blood_ground_backup',sid+scorebytes,856),('frontend',sid+scorebytes+856,menu),('rollback',129024,2048)]
for (left,a,n),(right,b,m) in zip(regions,regions[1:]):assert a+n<=b,(left,a,n,right,b,m,split)
assert regions[-1][1]+regions[-1][2]<=131072
assert (sid+scorebytes+856)>>16==1 and ((sid+scorebytes+856)&65535)+menu<=65536,'Menu reader assumes SPI bank 1'
defs={'BARB_VIEW_W':160,'BARB_VIEW_H':128,'BARB_WORLD_W':214,'BARB_FB_ROW_BYTES':107,'BARB_FB_BYTES':frame,
 'BARB_SPIVRAM_DISPLAY':0,'BARB_SPIVRAM_BG_CLEAN':frame*2,'BARB_SPIVRAM_SPRITES':pose_base,'BARB_RUNTIME_BASE':runtime_base,'BARB_RUNTIME_BYTES':runtime,
 'BARB_SPR_RESIDENT_BYTES':poses,'BARB_POSE_DIRECTORY_OFFSET':resident['directory_offset'],
 'BARB_SPR_BANK0_BYTES':split,'BARB_SPR_BANK1_BASE':tail,'BARB_SPR_FILE_BYTES':sprites,
 'BARB_MENU_FILE_OFFSET':poses+runtime,'BARB_MENU_SPI_BASE':sid+scorebytes+856,'BARB_MENU_BYTES':menu,
 'BARB_BG_FLOOR_LEFT':sid+scorebytes,'BARB_ROLLBACK_BASE':129024,
 'BARB_MUSIC_AHEAD_BASE':ahead,'BARB_MUSIC_AHEAD_BYTES':128,
 'BARB_SID_SPI_A':sid,'BARB_SID_RING_BYTES':1024,'BARB_SCORE_BYTES':scorebytes,'BARB_SCORE_SPI_BASE':sid,'BARB_WORKBUF_BYTES':max(512,cache)}
(R/'data/platform-layout.h').write_text('/* Generated by tools/prepare_layout.py. */\n#pragma once\n'+
 ''.join(f'#define {k} {v}UL\n' for k,v in defs.items()))
report=dict(regions=[dict(name=n,address=a,bytes=b) for n,a,b in regions],
 reserved=sum(n for _,_,n in regions),free=131072-sum(n for _,_,n in regions),
 sprite_cache_bytes=cache,work_buffer_bytes=max(512,cache))
(R/'data/platform-layout.json').write_text(json.dumps(report,indent=2)+'\n')
print('SPI layout:',report['reserved'],'reserved,',report['free'],'free; sprite split',split)
